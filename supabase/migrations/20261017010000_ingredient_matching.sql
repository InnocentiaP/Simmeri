-- =========================================================
-- Phase 2 — smart ingredient matching.
--
-- 1. user_ingredient_links: a user's own "these two names are the same
--    ingredient for me" links (e.g. "cabe" → "cabai merah"). Owner-only.
-- 2. A broader global catalog of common ingredients with English and
--    Indonesian aliases, extending the 20260803010000 seed.
--
-- Matching is computed when data is read (src/lib/ingredients/matcher.ts);
-- nothing is added to recipe_ingredients or kitchen_items, so recipe saves
-- and existing data are untouched. Purely additive and idempotent.
--
-- Catalog rules (unchanged from the original seed): one global alias maps
-- to exactly one canonical ingredient; ambiguous words are left out entirely
-- rather than guessed ("cabai" alone, "pepper", "merica"/"lada" (usually white
-- pepper in Indonesian recipes), "cheese", "cornflour",
-- "noodles", "fish"); distinct products stay separate (garlic vs garlic
-- powder, raw vs cooked rice, soy sauce vs sweet soy sauce, palm sugar vs
-- brown sugar, Indonesian bay leaf vs bay leaf).
-- =========================================================

CREATE TABLE public.user_ingredient_links (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Both stored normalized (lowercase, trimmed, accents stripped) by the app.
  alias_normalized text NOT NULL,
  target_normalized text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_ingredient_links_not_self CHECK (alias_normalized <> target_normalized),
  CONSTRAINT user_ingredient_links_alias_length CHECK (char_length(alias_normalized) BETWEEN 1 AND 200),
  CONSTRAINT user_ingredient_links_target_length CHECK (char_length(target_normalized) BETWEEN 1 AND 200),
  CONSTRAINT user_ingredient_links_unique UNIQUE (user_id, alias_normalized)
);
GRANT SELECT, INSERT, DELETE ON public.user_ingredient_links TO authenticated;
GRANT ALL ON public.user_ingredient_links TO service_role;
ALTER TABLE public.user_ingredient_links ENABLE ROW LEVEL SECURITY;
CREATE POLICY "user_ingredient_links_select_own" ON public.user_ingredient_links
  FOR SELECT TO authenticated USING (auth.uid() = user_id);
CREATE POLICY "user_ingredient_links_insert_own" ON public.user_ingredient_links
  FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);
CREATE POLICY "user_ingredient_links_delete_own" ON public.user_ingredient_links
  FOR DELETE TO authenticated USING (auth.uid() = user_id);

